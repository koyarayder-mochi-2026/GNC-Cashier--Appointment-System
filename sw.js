/* GNC cashier queue web-push service worker. */
self.addEventListener('install', (event) => { event.waitUntil(self.skipWaiting()); });
self.addEventListener('activate', (event) => { event.waitUntil(self.clients.claim()); });
self.addEventListener('push', (event) => {
  let payload = {};
  try { payload = event.data ? event.data.json() : {}; }
  catch { payload = { body: event.data ? event.data.text() : 'Your cashier queue number is being called.' }; }
  const title = payload.title || 'GNC Cashier Queue';
  const options = {
    body: payload.body || 'Your number is being called. Please proceed to the cashier.',
    icon: payload.icon || '/assets/gnc-official-crest.png',
    badge: payload.badge || '/assets/gnc-official-crest.png',
    tag: payload.tag || 'gnc-queue-turn',
    renotify: false,
    requireInteraction: true,
    data: { url: payload.url || '/' }
  };
  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const targetUrl = new URL(event.notification.data?.url || '/', self.location.origin).href;
  event.waitUntil((async () => {
    const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    for (const client of windows) {
      if (client.url.startsWith(self.location.origin) && 'focus' in client) {
        await client.focus();
        if ('navigate' in client) await client.navigate(targetUrl);
        return;
      }
    }
    if (self.clients.openWindow) await self.clients.openWindow(targetUrl);
  })());
});
